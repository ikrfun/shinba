// Run with node_modules/.bin/electron tests/electron-board-e2e.cjs after npm run build.
const { app, BrowserWindow, ipcMain } = require('electron');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const { registerStorage } = require('../app/main/storage.cjs');
const sessions = require('../app/cli/sessions.cjs');
const { writeJson, readBoard } = require('../app/cli/board.cjs');
const { watchBoard } = require('../app/main/board-watch.cjs');
let root, win;
let failDraft = false;
const pause = ms => new Promise(resolve => setTimeout(resolve,ms));
async function waitFor(expression, description) {
  for (let i=0;i<100;i++) { if (await win.webContents.executeJavaScript(expression)) return; await pause(100); }
  throw Error(`Timed out waiting for ${description}`);
}
async function run() {
  root = await fs.mkdtemp(path.join(os.tmpdir(),'shinba-electron-e2e-'));
  app.setPath('userData',path.join(root,'user-data'));
  const project=path.join(root,'project'), boardFile=path.join(project,'.shinba','boards','main.json');
  await fs.mkdir(path.dirname(boardFile),{recursive:true});
  await writeJson(boardFile,{id:'main',name:'Main',schemaVersion:1,revision:1,nodes:[{id:'a',type:'card',position:{x:0,y:0},data:{title:'First',body:'old'},style:{width:260,height:200}}],edges:[]});
  registerStorage({ipcMain:{handle(name, handler) {
    ipcMain.handle(name, (...args) => {
      if (name === 'board:draft-write' && failDraft) throw new Error('simulated draft write failure');
      return handler(...args);
    });
  }},inside:(p='')=>path.join(project,p)});
  ipcMain.handle('settings:get',()=>({vimEnabled:true,theme:'dark'}));
  ipcMain.handle('settings:set-theme',()=>{}); ipcMain.handle('settings:set-vim',()=>{});
  ipcMain.handle('project:open',()=>({name:'project',path:project}));
  win=new BrowserWindow({width:1100,height:750,show:false,webPreferences:{preload:path.resolve('app/main/preload.cjs'),contextIsolation:true,nodeIntegration:false}});
  const watcher=await watchBoard(project,()=>win.webContents.send('board:changed',project));
  win.webContents.on('console-message',(_e,level,message)=>{ if(level>=2) console.error('renderer:',message); });
  await win.loadFile(path.resolve('dist/index.html'));
  const open = async () => { win.webContents.send('shortcut','open-project'); await waitFor("document.querySelector('.card-view-body')?.textContent === 'old' || !!document.querySelector('.card-view-body')",'project'); };
  await open();
  const js = source => win.webContents.executeJavaScript(source);
  await waitFor("document.querySelector('.toolbar')?.textContent.includes('NORMAL')",'normal mode');
  const textPoint=await js(`(() => { const r=document.querySelector('.card-view-body').getBoundingClientRect(); return {x:Math.round((r.left+r.right)/2),y:Math.round((r.top+r.bottom)/2)} })()`);
  const beforeDrag=await js(`document.querySelector('.react-flow__node').getBoundingClientRect().left`);
  win.webContents.sendInputEvent({type:'mouseMove',x:textPoint.x,y:textPoint.y});
  win.webContents.sendInputEvent({type:'mouseDown',x:textPoint.x,y:textPoint.y,button:'left',clickCount:1});
  await pause(100);
  for (let i=1;i<=5;i++) { win.webContents.sendInputEvent({type:'mouseMove',x:textPoint.x+16*i,y:textPoint.y+8*i,button:'left'}); await pause(30); }
  win.webContents.sendInputEvent({type:'mouseUp',x:textPoint.x+80,y:textPoint.y+40,button:'left',clickCount:1});
  await waitFor(`Math.abs(document.querySelector('.react-flow__node').getBoundingClientRect().left - ${beforeDrag}) > 10`,'dragging from card text');
  await js("window.dispatchEvent(new KeyboardEvent('keydown',{key:'i',bubbles:true}))");
  await waitFor("document.querySelectorAll('.card textarea').length === 1",'insert mode');
  await js(`(() => { const e=document.querySelector('.card textarea'); Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(e,'human'); e.dispatchEvent(new Event('input',{bubbles:true})); })()`);
  await waitFor("document.querySelector('.toolbar')?.textContent.includes('unpublished')",'dirty draft');
  await pause(1000);
  await js("document.querySelector('.card textarea').focus()");
  const duringTyping=await sessions.begin(project), titleChange=structuredClone(duringTyping.board);
  titleChange.nodes[0].data.title='remote title';
  await sessions.update(project,duringTyping.id,titleChange); await sessions.commit(project,duringTyping.id);
  await waitFor("document.querySelector('.toolbar')?.textContent.includes('changed externally')",'deferred update');
  assert.equal(await js("document.querySelector('.card textarea').value"),'human');
  // The CI window is not OS-focused; dispatch focusout explicitly after blur.
  await js("(() => { const e=document.querySelector('.card textarea'); e.blur(); e.dispatchEvent(new FocusEvent('focusout',{bubbles:true})); })()");
  await waitFor("document.querySelector('.card input.title')?.value === 'remote title'",'refresh after leaving input');
  await js("window.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))");
  await waitFor("document.querySelector('.card-view-title')?.textContent === 'remote title'",'normal mode after editing');
  assert.equal((await readBoard(boardFile)).nodes[0].data.body,'old');
  const sessionId=await js(`localStorage.getItem(${JSON.stringify('shinba:board-session:'+project)})`);
  assert.equal((await sessions.useSession(project,sessionId,state=>state)).working.nodes[0].data.body,'human');
  await win.webContents.reload(); await pause(500); await open();
  assert.equal(await js("document.querySelector('.card-view-body').textContent.trim()"),'human');
  const agent=await sessions.begin(project), remote=structuredClone(agent.board);
  remote.nodes[0].data.body='agent'; await sessions.update(project,agent.id,remote); await sessions.commit(project,agent.id);
  await waitFor("document.querySelector('.toolbar')?.textContent.includes('changed externally')",'external change');
  await waitFor("![...document.querySelectorAll('.toolbar button')].find(b=>b.textContent==='Save board').disabled",'external check');
  await js("window.dispatchEvent(new KeyboardEvent('keydown',{key:':',bubbles:true}))");
  await waitFor("!!document.querySelector('input[aria-label=\"Board command\"]')",'command line');
  await js(`(() => { const e=document.querySelector('input[aria-label="Board command"]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(e,'w'); e.dispatchEvent(new Event('input',{bubbles:true})); e.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true})); })()`);
  await waitFor("!!document.querySelector('[role=dialog]')",'conflict dialog');
  await fs.writeFile('/private/tmp/shinba-e2e-conflict.png',(await win.capturePage()).toPNG());
  assert.match(await js("document.querySelector('[role=dialog]').innerText"),/human/);
  assert.match(await js("document.querySelector('[role=dialog]').innerText"),/agent/);
  await js("[...document.querySelectorAll('.conflict-item button')].find(x=>x.textContent==='Edit result').click()");
  await js(`(() => { const e=document.querySelector('.conflict-item textarea'); Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(e,'human + agent'); e.dispatchEvent(new Event('input',{bubbles:true})); })()`);
  await js("[...document.querySelectorAll('.conflict-dialog footer button')].find(x=>x.textContent==='Save resolved board').click()");
  await waitFor("!document.querySelector('[role=dialog]')",'resolved save');
  assert.equal((await readBoard(boardFile)).nodes[0].data.body,'human + agent');
  const next=await sessions.begin(project), remote2=structuredClone(next.board); remote2.nodes[0].data.body='refreshed';
  await sessions.update(project,next.id,remote2); await sessions.commit(project,next.id);
  await waitFor("document.querySelector('.card-view-body')?.textContent.trim() === 'refreshed'",'clean refresh');
  await js("[...document.querySelectorAll('.toolbar button')].find(x=>x.textContent.includes('Card')).click()");
  await waitFor("document.querySelectorAll('.react-flow__node').length === 2",'new card');
  const distances=await js(`(() => { const flow=document.querySelector('.react-flow').getBoundingClientRect(); const n=[...document.querySelectorAll('.react-flow__node')].at(-1).getBoundingClientRect(); return {x:Math.abs((flow.left+flow.right)/2-(n.left+n.right)/2), y:Math.abs((flow.top+flow.bottom)/2-(n.top+n.bottom)/2)} })()`);
  assert.ok(distances.x < 5 && distances.y < 5,JSON.stringify(distances));
  const stacking=await js(`([...document.querySelectorAll('.react-flow__node')]).map(n=>Number(getComputedStyle(n).zIndex)||0)`);
  assert.ok(stacking[1] > stacking[0],JSON.stringify(stacking));
  await pause(1000);
  const independent=await sessions.begin(project), remote3=structuredClone(independent.board);
  remote3.nodes[0].data.body='remote with local draft';
  await sessions.update(project,independent.id,remote3); await sessions.commit(project,independent.id);
  await waitFor("document.querySelector('.card-view-body')?.textContent.trim() === 'remote with local draft'",'non-conflicting refresh');
  assert.equal(await js("document.querySelectorAll('.react-flow__node').length"),2);
  assert.equal((await readBoard(boardFile)).nodes.length,1);
  assert.equal((await sessions.useSession(project,sessionId,state=>state)).working.nodes.length,2);
  failDraft=true;
  await js("window.dispatchEvent(new KeyboardEvent('keydown',{key:':',bubbles:true}))");
  await waitFor("!!document.querySelector('input[aria-label=\"Board command\"]')",'card command line');
  await js(`(() => { const e=document.querySelector('input[aria-label="Board command"]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(e,'ac html'); e.dispatchEvent(new Event('input',{bubbles:true})); e.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true})); })()`);
  await waitFor("!!document.querySelector('iframe.card-html-preview[sandbox]')",'HTML card');
  await waitFor("[...document.querySelectorAll('.toolbar button')].some(b=>b.textContent==='Retry draft save')",'draft error recovery');
  assert.equal((await readBoard(boardFile)).nodes.length,1);
  failDraft=false;
  await js("[...document.querySelectorAll('.toolbar button')].find(b=>b.textContent==='Retry draft save').click()");
  await waitFor("![...document.querySelectorAll('.toolbar button')].some(b=>b.textContent==='Retry draft save')",'draft save retry');
  await js("[...document.querySelectorAll('.toolbar button')].find(b=>b.textContent==='Save board').click()");
  await waitFor("document.querySelector('.toolbar').textContent.includes('Board up to date')",'save after draft failure');
  assert.equal((await readBoard(boardFile)).nodes.length,3);
  watcher.close();
  console.log('Electron board workflow passed');
}
app.whenReady().then(run).then(async()=>{ await fs.rm(root,{recursive:true,force:true}); app.exit(0); }).catch(async e=>{ console.error(e); if(root) console.error('Fixture retained:',root); app.exit(1); });
