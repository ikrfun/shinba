const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { status, fileRanges } = require('../app/main/git-status.cjs');
const git = (cwd, ...args) => execFileSync('git', ['-C', cwd, ...args], { stdio: 'pipe' });

test('Git status detects local and unpushed changes and symbol line ranges', async t => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'shinba-git-'));
  t.after(() => fs.rm(dir, { recursive: true, force: true }));
  git(dir, 'init', '-q');
  git(dir, 'config', 'user.email', 'test@example.com');
  git(dir, 'config', 'user.name', 'Test');
  await fs.mkdir(path.join(dir, 'src'));
  const file = path.join(dir, 'src', 'example.js');
  await fs.writeFile(file, 'function first() {\n  return 1;\n}\n\nfunction second() {\n  return 2;\n}\n');
  git(dir, 'add', '.'); git(dir, 'commit', '-qm', 'base');
  assert.equal((await status(dir)).upstream, false);
  git(dir, 'branch', 'upstream');
  git(dir, 'config', 'branch.master.remote', '.');
  git(dir, 'config', 'branch.master.merge', 'refs/heads/upstream');
  // Use the current branch name rather than assuming the Git default.
  const branch = git(dir, 'branch', '--show-current').toString().trim();
  git(dir, 'config', `branch.${branch}.remote`, '.');
  git(dir, 'config', `branch.${branch}.merge`, 'refs/heads/upstream');
  await fs.writeFile(file, 'function first() {\n  return 3;\n}\n\nfunction second() {\n  return 2;\n}\n');
  git(dir, 'add', '.'); git(dir, 'commit', '-qm', 'change first');
  let state = await status(dir);
  assert.equal(state.upstream, true);
  assert.equal(state.files['src/example.js'].unpushed, true);
  assert.deepEqual((await fileRanges(dir, 'src/example.js', state.files['src/example.js'])).unpushed, [{ start: 1, end: 1 }]);
  await fs.writeFile(file, 'function first() {\n  return 3;\n}\n\nfunction second() {\n  return 4;\n}\n');
  await fs.writeFile(path.join(dir, 'src', 'new.js'), 'new');
  await fs.writeFile(path.join(dir, '.gitignore'), 'build/\n*.tmp\n');
  await fs.mkdir(path.join(dir, 'build'));
  await fs.writeFile(path.join(dir, 'build', 'output.js'), 'generated');
  await fs.writeFile(path.join(dir, 'src', 'cache.tmp'), 'cache');
  state = await status(dir);
  assert.equal(state.files['src/example.js'].modified, true);
  assert.equal(state.files['src/new.js'].modified, true);
  assert.equal(state.files.build.ignored, true);
  assert.equal(state.files['src/cache.tmp'].ignored, true);
  assert.deepEqual((await fileRanges(dir, 'src/example.js', state.files['src/example.js'])).modified, [{ start: 5, end: 5 }]);
  assert.equal((await fileRanges(dir, 'src/new.js', state.files['src/new.js'])).modified[0].start, 0);
  const subdir = await status(path.join(dir, 'src'));
  assert.equal(subdir.files['example.js'].modified, true);
  assert.equal(subdir.files['example.js'].unpushed, true);
  assert.equal(subdir.files['cache.tmp'].ignored, true);
});
